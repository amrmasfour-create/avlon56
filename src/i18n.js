export function t(lang, key) {
  const e = T[key];
  if (!e) return key;
  return lang === 'en' ? e[1] : e[0];
}

/** Pick a bilingual DB column: L(row,'name',lang) → row.name_ar / row.name_en, with fallback. */
export function L(row, field, lang) {
  if (!row) return '';
  const v = row[`${field}_${lang}`];
  return v || row[`${field}_${lang === 'en' ? 'ar' : 'en'}`] || '';
}

export function dict(lang) {
  const o = {};
  for (const k of Object.keys(T)) o[k] = t(lang, k);
  return o;
}
